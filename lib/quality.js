/**
 * 质量读模型（只读）：把 kb_lint 的机械分组转成工作台「质量队列」。
 *
 * 设计边界（见 docs/plans/2026-11-02-0.36-data-quality-plan.md）：
 *  - 判定逻辑只有一个来源：lintManifest。这里不复制任何判定条件，只做
 *    分组元数据、证据补齐、组内筛选/分页；计数与 kb_lint 逐组一致。
 *  - 不做语义判断：不决定某篇该不该 OCR、摘要该怎么写、标准号该不该改。
 *  - 不写任何文件：纯函数，输入 manifest，输出 JSON 可序列化对象。
 *
 * 两个「补充检查」是 lintManifest 没有的（属于编译层/身份层的人工队列），
 * 复用既有纯函数，标为 extra 分区，不参与 kb_lint 对账：
 *  - summary-noise：摘要疑似 OCR 页眉/英文版权页（looksNoisySummary，空摘要
 *    不算，空的已在 unlabeled 里，避免同一篇报两次）；
 *  - no-standard-no：资料没有标准号（规章/通知/内部稿本来就没有，需人工判断）。
 */
import { lintManifest } from "./lint.js";
import { looksNoisySummary } from "./summary-candidates.js";

/** 单次 lint 取回的明细上限：保证 count/matched/分页基于完整列表。 */
const LINT_ITEM_CAP = 5000;

/** 自动生成的索引页（如「标准索引（自动生成）」）不是标准资料，不计入身份层。 */
const AUTO_GENERATED_TITLE = /[（(]\s*自动生成\s*[）)]\s*$/;

const SEVERITY_RANK = { error: 0, warning: 1, info: 2 };

const FALLBACK_META = Object.freeze({
  section: "state",
  actionable: false,
  deferred: false,
  suggestedAction: null,
  allowedActions: [],
});

/**
 * 分组元数据。order 决定同 severity 内的展示顺序（越小越靠前）。
 * actionable=true 只给「工作台动作白名单里能直接执行」的组；需要脚本或人工
 * 判断的组（元数据回填、标准号、笔记合并、缺规范）保持 false，只给 hint。
 */
const GROUP_META = Object.freeze({
  failed: { section: "state", actionable: true, order: 10, suggestedAction: "retry-import", allowedActions: ["retry-import", "remove"] },
  stale: { section: "state", actionable: false, deferred: true, order: 20 },
  corrupted: { section: "content", actionable: true, order: 30, suggestedAction: "reparse-pages", allowedActions: ["reparse-pages"] },
  "content-incomplete": { section: "content", actionable: true, order: 35, suggestedAction: "reparse-pages", allowedActions: ["reparse-pages"] },
  "summary-noise": { section: "compiled", actionable: true, order: 40, suggestedAction: "describe", allowedActions: ["describe"] },
  "duplicate-content": { section: "duplicate", actionable: true, order: 50, suggestedAction: "keep", allowedActions: ["keep", "remove"] },
  "duplicate-text": { section: "duplicate", actionable: true, order: 55, suggestedAction: "keep", allowedActions: ["keep", "remove"] },
  "same-number": { section: "duplicate", actionable: true, order: 60, suggestedAction: "keep", allowedActions: ["keep", "remove"] },
  "same-number-stages": { section: "duplicate", actionable: false, order: 65 },
  "same-number-multi-year": { section: "duplicate", actionable: false, order: 70 },
  "same-number-family": { section: "duplicate", actionable: true, order: 75, suggestedAction: "keep", allowedActions: ["keep", "remove"] },
  "temp-files": { section: "state", actionable: true, order: 80, suggestedAction: "remove", allowedActions: ["remove"] },
  "metadata-missing": { section: "identity", actionable: false, order: 85 },
  "filename-standard-mismatch": { section: "identity", actionable: false, order: 90 },
  "no-standard-no": { section: "identity", actionable: false, order: 95 },
  unlabeled: { section: "compiled", actionable: true, order: 100, suggestedAction: "describe", allowedActions: ["describe"] },
  "note-no-sources": { section: "compiled", actionable: false, order: 105 },
  "supersede-hint": { section: "compiled", actionable: false, order: 110 },
  "orphan-note": { section: "compiled", actionable: false, order: 112 },
  "note-stale": { section: "compiled", actionable: false, order: 115 },
  "trust-unknown": { section: "compiled", actionable: true, order: 120, suggestedAction: "trust", allowedActions: ["trust"] },
  "schema-missing": { section: "state", actionable: false, order: 130 },
});

/** 只读分组元数据（供 UI/测试引用；不要就地修改）。 */
export const QUALITY_GROUP_META = GROUP_META;

/** 文档是否为插件/脚本自动生成的索引页（不是标准资料）。 */
export function isAutoGeneratedDoc(doc) {
  const title = String(doc?.title ?? "");
  return AUTO_GENERATED_TITLE.test(title.trim()) || doc?.generated === true;
}

function isPageNumber(value) {
  return Number.isInteger(value) && value > 0;
}

function pageList(value) {
  if (!Array.isArray(value)) return [];
  return value.filter(isPageNumber);
}

function pageSet(...lists) {
  const pages = new Set();
  for (const list of lists) for (const page of list) pages.add(page);
  return [...pages].sort((a, b) => a - b);
}

function hasSummary(doc) {
  return String(doc?.summary ?? "").trim() !== "";
}

function isAutoGeneratedIndex(manifest) {
  return (manifest?.docs ?? []).some((doc) => doc?.type === "markdown" && isAutoGeneratedDoc(doc));
}

/**
 * 总览徽标用的轻量计数：只读文档字段（不跑 lint、不读正文），
 * 给库列表/总览卡片一个「这个库有多少质量问题」的提示。
 */
export function countQualityFlags(docs = []) {
  const counters = {
    failed: 0,
    corruptedDocs: 0,
    lowConfidenceDocs: 0,
    contentIncomplete: 0,
    unlabeled: 0,
    summaryNoise: 0,
    noStandardNo: 0,
  };
  for (const doc of Array.isArray(docs) ? docs : []) {
    if (doc?.status === "failed") counters.failed += 1;
    if (doc?.status !== "ready" || doc?.deletedAt) continue;
    const isNote = doc.type === "note";
    if (!isNote && pageList(doc.corruptedPages).length > 0) counters.corruptedDocs += 1;
    if (!isNote && pageList(doc.lowConfidencePages).length > 0) counters.lowConfidenceDocs += 1;
    if (!isNote && ["partial", "cover-only"].includes(doc.contentIntegrity)) counters.contentIncomplete += 1;
    if (!hasSummary(doc)) counters.unlabeled += 1;
    if (isNote || isAutoGeneratedDoc(doc)) continue;
    if (hasSummary(doc) && looksNoisySummary(doc.summary)) counters.summaryNoise += 1;
    if (!String(doc.standardNo ?? "").trim()) counters.noStandardNo += 1;
  }
  return counters;
}

/** 解析 lint item 的 docId（重复类分组是逗号拼接的字符串）。 */
function parseDocIds(docId) {
  return String(docId ?? "")
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);
}

/** 单篇证据：坏页、正文完整性、可信度、缺摘要等，供工作台展开行直接展示。 */
function evidenceOf(doc, id) {
  if (!doc) return { id, title: "", missing: true };
  const corruptedPages = pageList(doc.corruptedPages);
  const lowConfidencePages = pageList(doc.lowConfidencePages);
  return {
    id: doc.id ?? id,
    title: String(doc.title ?? ""),
    status: String(doc.status ?? ""),
    type: String(doc.type ?? ""),
    pages: Number(doc.pages) || 0,
    badPages: pageSet(corruptedPages, lowConfidencePages),
    corruptedPages,
    lowConfidencePages,
    contentIntegrity: String(doc.contentIntegrity ?? "unknown"),
    trust: String(doc.trust ?? "unknown"),
    summaryMissing: !hasSummary(doc),
    standardNo: String(doc.standardNo ?? ""),
    stage: String(doc.stage ?? "unknown"),
    version: Number(doc.version) || 0,
    updatedAt: String(doc.updatedAt ?? ""),
    ocrConfidence: Number.isFinite(doc.ocrConfidence) ? doc.ocrConfidence : null,
  };
}

/**
 * 展开一条 lint 明细：补充 docs[] 证据；单篇组的证据同时提升到顶层
 * （与计划里的 item 形状一致），多篇组只给 docs[]，避免“页码指谁的”歧义。
 */
function expandItem(item, byId) {
  const docIds = Array.isArray(item.docIds) && item.docIds.length > 0
    ? item.docIds.map((id) => String(id))
    : parseDocIds(item.docId);
  const docs = docIds.map((id) => evidenceOf(byId.get(id), id));
  const expanded = {
    docId: String(item.docId ?? ""),
    docIds,
    title: String(item.title ?? docs[0]?.title ?? ""),
    detail: String(item.detail ?? ""),
    docs,
  };
  if (docs.length === 1 && docs[0].missing !== true) {
    const only = docs[0];
    expanded.pages = only.pages;
    expanded.badPages = only.badPages;
    expanded.contentIntegrity = only.contentIntegrity;
    expanded.trust = only.trust;
    expanded.summaryMissing = only.summaryMissing;
    expanded.standardNo = only.standardNo;
    expanded.stage = only.stage;
    expanded.status = only.status;
    expanded.type = only.type;
    expanded.version = only.version;
    expanded.updatedAt = only.updatedAt;
    expanded.ocrConfidence = only.ocrConfidence;
  }
  return expanded;
}

function decorateGroup(raw, byId) {
  const meta = GROUP_META[raw.code] ?? FALLBACK_META;
  const items = (Array.isArray(raw.items) ? raw.items : []).map((item) => expandItem(item, byId));
  const total = Number.isFinite(raw.count) ? raw.count : items.length;
  return {
    code: String(raw.code ?? ""),
    label: String(raw.label ?? raw.code ?? ""),
    severity: String(raw.severity ?? "info"),
    section: meta.section ?? "state",
    actionable: meta.actionable === true,
    deferred: meta.deferred === true,
    suggestedAction: meta.suggestedAction ?? null,
    allowedActions: Array.isArray(meta.allowedActions) ? [...meta.allowedActions] : [],
    hint: String(raw.hint ?? ""),
    count: Math.max(total, items.length),
    sourceTruncated: total > items.length,
    items,
  };
}

function matchesQuery(item, query) {
  if (!query) return true;
  const haystack = [
    item.title,
    item.docId,
    item.detail,
    ...(item.docs ?? []).map((doc) => `${doc.title} ${doc.standardNo ?? ""}`),
  ].join(" ").toLowerCase();
  return haystack.includes(query);
}

function paginateGroup(group, { query, offset, limit, includeDeferred }) {
  const matched = query ? group.items.filter((item) => matchesQuery(item, query)) : group.items;
  const hidden = group.deferred && !includeDeferred;
  const start = hidden ? 0 : Math.min(offset, matched.length);
  const items = hidden ? [] : matched.slice(start, start + limit);
  return {
    ...group,
    items,
    matched: matched.length,
    offset: hidden ? 0 : start,
    limit,
    returned: items.length,
    truncated: hidden
      ? group.sourceTruncated
      : group.sourceTruncated || matched.length > start + items.length,
  };
}

function intOption(value, fallback, min, max) {
  if (value === undefined || value === null) return fallback;
  const text = String(value).trim();
  if (text === "" || !Number.isFinite(Number(text))) return fallback;
  return Math.min(max, Math.max(min, Math.round(Number(text))));
}

function boolOption(value) {
  return value === true || value === "true" || value === "1";
}

/** 补充检查：返回与 lint 分组同形的原始分组（统一走同一套证据/分页逻辑）。 */
function buildExtraGroups(docs) {
  const sources = docs.filter((doc) => doc.type !== "note" && !isAutoGeneratedDoc(doc));
  const groups = [];

  const noisy = sources.filter((doc) => hasSummary(doc) && looksNoisySummary(doc.summary));
  if (noisy.length > 0) {
    groups.push({
      severity: "warning",
      code: "summary-noise",
      label: "摘要疑似噪声（OCR 页眉/英文版权页）",
      count: noisy.length,
      items: noisy.map((doc) => ({
        docId: doc.id,
        title: doc.title,
        detail: String(doc.summary ?? "").replace(/\s+/g, " ").trim().slice(0, 80),
      })),
      hint: "打开前 1–2 页找「本文件规定了/适用于」，人工写 1–2 句；正文抽不到时用封面标题，不自动生成",
    });
  }

  const noStd = sources.filter((doc) => !String(doc.standardNo ?? "").trim());
  if (noStd.length > 0) {
    groups.push({
      severity: "info",
      code: "no-standard-no",
      label: "无标准号（需人工判断是否补号）",
      count: noStd.length,
      items: noStd.map((doc) => ({
        docId: doc.id,
        title: doc.title,
        detail: `${doc.type ?? "unknown"}｜${doc.stage ?? "unknown"}`,
      })),
      hint: "规章/通知/内部稿/征求意见稿不补号；标准类必须有封面证据，正式号未知不要编造",
    });
  }

  return groups;
}

function orderOf(code) {
  return GROUP_META[code]?.order ?? 999;
}

function summarizeGroups(groups, base) {
  const summary = {
    ...base,
    groups: groups.length,
    error: 0,
    warning: 0,
    info: 0,
    actionable: 0,
    actionableGroups: 0,
    deferred: 0,
    deferredItems: 0,
  };
  const actionableDocs = new Set();
  for (const group of groups) {
    if (group.deferred) {
      summary.deferred += 1;
      summary.deferredItems += group.count;
      continue;
    }
    if (group.severity === "error") summary.error += group.count;
    else if (group.severity === "warning") summary.warning += group.count;
    else summary.info += group.count;
    if (!group.actionable) continue;
    summary.actionableGroups += 1;
    for (const item of group.items) for (const id of item.docIds) actionableDocs.add(id);
  }
  summary.actionable = actionableDocs.size;
  return summary;
}

/**
 * 构建质量读模型。
 *
 * @param manifest 知识库清单（readManifest/tryReadManifest 的返回值）
 * @param options {kbName, hasSchema, now, staleDays, maxItems, offset, limit,
 *                 group, severity, query, actionableOnly, includeDeferred}
 *  - maxItems：每组最多返回多少条明细（1–200，默认 50），count 始终是总数；
 *  - offset/limit：组内分页，limit 缺省等于 maxItems；
 *  - group：只返回该组（并强制加载 deferred 组明细）；
 *  - severity：error/warning/info 逗号或空格分隔；
 *  - actionableOnly：只看可机械执行的组；
 *  - includeDeferred：连 deferred 组的明细一起返回。
 */
export function buildQualityReport(manifest, options = {}) {
  const docs = Array.isArray(manifest?.docs) ? manifest.docs : [];
  const kbName = String(options.kbName ?? manifest?.name ?? "");
  const now = Number.isFinite(Number(options.now)) ? Number(options.now) : Date.now();
  const staleDays = intOption(options.staleDays, 90, 0, 3650);
  const maxItems = intOption(options.maxItems, 50, 1, 200);
  const offset = intOption(options.offset, 0, 0, 1_000_000);
  const limit = intOption(options.limit, maxItems, 1, 200);
  const groupFilter = String(options.group ?? "").trim();
  const query = String(options.query ?? "").trim().toLowerCase();
  const actionableOnly = boolOption(options.actionableOnly ?? options.actionable);
  const includeDeferred = boolOption(options.includeDeferred);
  const severityFilter = new Set(
    String(options.severity ?? "")
      .split(/[,，\s]+/)
      .map((part) => part.trim().toLowerCase())
      .filter((part) => SEVERITY_RANK[part] !== undefined)
  );

  const byId = new Map(docs.map((doc) => [doc.id, doc]));
  const lint = lintManifest(manifest, {
    kbName,
    hasSchema: options.hasSchema !== false,
    now,
    staleDays,
    maxItems: LINT_ITEM_CAP,
  });

  const ready = docs.filter((doc) => doc.status === "ready" && !doc.deletedAt);
  const rawExtras = buildExtraGroups(ready);
  const allGroups = [...lint.groups, ...rawExtras].map((raw) => decorateGroup(raw, byId));

  allGroups.sort((a, b) => {
    const bySeverity = (SEVERITY_RANK[a.severity] ?? 9) - (SEVERITY_RANK[b.severity] ?? 9);
    return bySeverity !== 0 ? bySeverity : orderOf(a.code) - orderOf(b.code);
  });

  const summary = summarizeGroups(allGroups, {
    totalDocs: docs.length,
    readyDocs: ready.length,
    notes: ready.filter((doc) => doc.type === "note").length,
    sources: ready.filter((doc) => doc.type !== "note").length,
    readOnly: manifest?.readOnly === true,
    generatedAt: new Date(now).toISOString(),
  });

  const selected = allGroups
    .filter((group) => groupFilter === "" || group.code === groupFilter)
    .filter((group) => severityFilter.size === 0 || severityFilter.has(group.severity))
    .filter((group) => !actionableOnly || group.actionable)
    .map((group) => paginateGroup(group, {
      query,
      offset,
      limit,
      includeDeferred: includeDeferred || (groupFilter !== "" && groupFilter === group.code),
    }));

  return {
    kb: kbName,
    readOnly: manifest?.readOnly === true,
    generatedAt: summary.generatedAt,
    summary,
    groups: selected,
    totals: lint.totals,
    counts: lint.counts,
    truncated: selected.some((group) => group.truncated),
  };
}
