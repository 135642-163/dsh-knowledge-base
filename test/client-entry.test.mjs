/**
 * 客户端 bundle：DSH 侧栏入口。
 * 用 node:vm 模拟 __ModuleLoader__，不启动浏览器。
 */
import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bundle = await readFile(join(root, "lib/client.js"), "utf8");
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

function jsx(type, props, key) {
  return { type, props: props ?? {}, key: key ?? null };
}

function requireStub(id) {
  if (id === "react") return { createElement: jsx, Fragment: Symbol.for("react.fragment") };
  if (id === "react/jsx-runtime") return { jsx, jsxs: jsx, Fragment: Symbol.for("react.fragment") };
  if (id === "react-dom") return {};
  throw new Error(`unexpected require: ${id}`);
}

function loadClient(overrides = {}) {
  let entry;
  const context = {
    window: {
      __ModuleLoader__: { load(value) { entry = value; } },
      open: () => ({ closed: false }),
      ...(overrides.window ?? {}),
    },
    document: overrides.document,
    console,
  };
  vm.runInNewContext(bundle, context, { filename: "lib/client.js" });
  assert.ok(entry, "bundle did not call __ModuleLoader__.load");
  const mod = entry.factory(requireStub);
  return { entry, mod, context };
}

function childrenOf(node) {
  const children = node?.props?.children;
  if (Array.isArray(children)) return children;
  return children === undefined || children === null ? [] : [children];
}

test("bundle metadata exposes a web client entry for the sidebar", () => {
  assert.equal(pkg.dsh.client.platform, "web");
  assert.deepEqual(pkg.dsh.client.inject, ["@deepseek-ai/dsh-client-ui-sidebar"]);
  assert.equal(pkg.exports["./client"], "./lib/client.js");
  assert.match(bundle, /^\/\/ Generated by scripts\/build-client\.mjs/);
  assert.match(bundle, /window\.__ModuleLoader__\.load/);
  assert.match(bundle, /require\("react\/jsx-runtime"\)/);
  assert.doesNotMatch(bundle, /__SECRET_INTERNALS_DO_NOT_USE_OR_YOU_WILL_BE_FIRED/);
});

test("apply registers sidebar.footer.action with kb-workbench", () => {
  const { mod } = loadClient();
  const calls = { inject: [], register: [] };
  const ctx = {
    slots: {
      inject(name, callback) { calls.inject.push(name); callback(); },
      register(decl, component) { calls.register.push({ decl, component }); },
    },
  };
  mod.apply(ctx);
  assert.deepEqual(calls.inject, ["sidebar.footer.action"]);
  assert.equal(calls.register.length, 1);
  assert.equal(calls.register[0].decl.name, "sidebar.footer.action");
  assert.equal(calls.register[0].decl.id, "kb-workbench");
  assert.equal(calls.register[0].decl.order, 10);
  assert.equal(typeof calls.register[0].component, "function");
});

test("component renders the label only when the sidebar is wide", () => {
  const { mod } = loadClient();
  let component;
  mod.apply({
    slots: {
      inject(_name, callback) { callback(); },
      register(_decl, value) { component = value; },
    },
  });

  const wide = component({ wide: true });
  assert.equal(wide.type, "button");
  assert.equal(wide.props.title, "知识库工作台");
  assert.equal(wide.props["aria-label"], "知识库工作台");
  assert.ok(childrenOf(wide).some((child) => child?.type === "span" && child.props?.children === "知识库"));

  const collapsed = component({ wide: false });
  assert.ok(!childrenOf(collapsed).some((child) => child?.type === "span"));
});

test("click opens /kb/ in a new tab", () => {
  const { mod, context } = loadClient();
  const opened = [];
  context.window.open = (...args) => { opened.push(args); return { closed: false }; };
  let component;
  mod.apply({
    slots: {
      inject(_name, callback) { callback(); },
      register(_decl, value) { component = value; },
    },
  });
  component({ wide: true }).props.onClick();
  assert.deepEqual(opened, [["/kb/", "_blank", "noopener,noreferrer"]]);
});

test("injects the sidebar CSS once", () => {
  const styles = [];
  const document = {
    querySelector(selector) {
      return styles.find((style) => selector.includes(style.dataset.pluginCss)) ?? null;
    },
    createElement() {
      return { dataset: {}, textContent: "" };
    },
    head: {
      appendChild(style) { styles.push(style); },
    },
  };
  const { mod } = loadClient({ document });
  const ctx = {
    slots: {
      inject(_name, callback) { callback(); },
      register() {},
    },
  };
  mod.apply(ctx);
  mod.apply(ctx);
  assert.equal(styles.length, 1);
  assert.match(styles[0].textContent, /\.dsh-kb-entry/);
});

test("bundle registers the loader entry id used by the profile", () => {
  const boot = (ids) => ({ __DSH_BOOT__: { entries: ids.map((id) => ({ id })) } });
  assert.equal(loadClient({ window: boot(["dsh-knowledge-base"]) }).entry.id, "dsh-knowledge-base");
  assert.equal(loadClient({ window: boot(["dsh-knowledge-wiki"]) }).entry.id, "dsh-knowledge-wiki");
  assert.equal(loadClient().entry.id, "dsh-knowledge-base");
});
