/**
 * 客户端 bundle：DSH 侧栏入口 + 工作台弹窗。
 * 用 node:vm 模拟 __ModuleLoader__，不启动浏览器。
 */
import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bundle = await readFile(join(root, "lib/client.js"), "utf8");
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

const Fragment = Symbol.for("react.fragment");

function jsx(type, props, key) {
  return { type, props: props ?? {}, key: key ?? null };
}

function fakeDocument(styles) {
  return {
    body: { style: {} },
    head: { appendChild(style) { styles.push(style); } },
    querySelector(selector) {
      return styles.find((style) => selector.includes(style.dataset.pluginCss)) ?? null;
    },
    createElement() {
      return { dataset: {}, textContent: "" };
    },
  };
}

function requireStub(id, state) {
  if (id === "react") {
    return {
      createElement: jsx,
      Fragment,
      useState(initial) {
        const setter = (next) => {
          state.open = typeof next === "function" ? next(state.open) : next;
        };
        state.setters.push(setter);
        return [state.open ?? initial, setter];
      },
      useEffect(effect) {
        state.effects.push(effect);
      },
      useRef(initial) {
        const ref = { current: initial };
        state.refs.push(ref);
        return ref;
      },
    };
  }
  if (id === "react/jsx-runtime") return { jsx, jsxs: jsx, Fragment };
  if (id === "react-dom") {
    return {
      createPortal(node, container) {
        state.portals.push({ node, container });
        return { type: "portal", node, container };
      },
    };
  }
  throw new Error(`unexpected require: ${id}`);
}

function loadClient(overrides = {}) {
  let entry;
  const state = {
    open: overrides.open ?? false,
    setters: [],
    effects: [],
    portals: [],
    refs: [],
    styles: [],
    document: undefined,
  };
  state.document = overrides.document === undefined ? undefined : overrides.document(state.styles);
  const context = {
    window: {
      __ModuleLoader__: { load(value) { entry = value; } },
      ...(overrides.window ?? {}),
    },
    document: state.document,
    console,
  };
  vm.runInNewContext(bundle, context, { filename: "lib/client.js" });
  assert.ok(entry, "bundle did not call __ModuleLoader__.load");
  const mod = entry.factory((id) => requireStub(id, state));
  return { entry, mod, context, state };
}

function childrenOf(node) {
  const children = node?.props?.children;
  if (Array.isArray(children)) return children;
  return children === undefined || children === null ? [] : [children];
}

function findChild(node, predicate) {
  return childrenOf(node).find(predicate);
}

function componentFor(mod, name) {
  let component;
  mod.apply({
    slots: {
      inject(_name, callback) { callback(); },
      register(decl, value) { if (decl.name === name) component = value; },
    },
  });
  return component;
}

function renderAction(mod, wide = true) {
  const tree = componentFor(mod, "sidebar.footer.action")({ wide });
  // 抽取 WorkbenchModal 后，侧栏树里的弹窗是子组件；这里展开一层，
  // 让下面「open state ... portal」用例仍能遍历到弹窗渲染的 portal。
  const children = childrenOf(tree).map((child) => (
    typeof child?.type === "function" ? child.type(child.props) : child
  ));
  return { ...tree, props: { ...tree.props, children } };
}

test("bundle metadata exposes a web client entry for the sidebar", () => {
  assert.equal(pkg.dsh.client.platform, "web");
  assert.deepEqual(pkg.dsh.client.inject, ["@deepseek-ai/dsh-client-ui-sidebar"]);
  assert.equal(pkg.exports["./client"], "./lib/client.js");
  assert.match(bundle, /^\/\/ Generated by scripts\/build-client\.mjs/);
  assert.match(bundle, /window\.__ModuleLoader__\.load/);
  assert.match(bundle, /require\("react\/jsx-runtime"\)/);
  assert.match(bundle, /require\("react-dom"\)/);
  assert.doesNotMatch(bundle, /__SECRET_INTERNALS_DO_NOT_USE_OR_YOU_WILL_BE_FIRED/);
});

test("apply registers sidebar and composer slots", () => {
  const { mod } = loadClient();
  const calls = { inject: [], register: [] };
  const ctx = {
    slots: {
      inject(name, callback) { calls.inject.push(name); callback(); },
      register(decl, component) { calls.register.push({ decl, component }); },
    },
  };
  mod.apply(ctx);
  assert.deepEqual(calls.inject, [
    "sidebar.footer.action",
    "conversation.input.left",
    "tool.call.toolview",
    "conversation.chat.turnTail",
    "conversation.chat.assistant-actions",
  ]);
  assert.deepEqual(calls.register.map((row) => [row.decl.name, row.decl.id ?? row.decl.key, row.decl.order]), [
    ["sidebar.footer.action", "kb-workbench", 10],
    ["conversation.input.left", "kb-scope", 20],
    ["tool.call.toolview", "kb_query", undefined],
    ["tool.call.toolview", "kb_read", undefined],
    ["conversation.chat.turnTail", "kb-sources", 30],
    ["conversation.chat.assistant-actions", "kb-citations", 20],
  ]);
  assert.equal(calls.register.every((row) => typeof row.component === "function"), true);
});

test("entry renders the label in wide mode and opens on click", () => {
  const { mod, state } = loadClient();
  const tree = renderAction(mod);
  const button = findChild(tree, (child) => child?.type === "button");
  assert.ok(button, "entry button missing");
  assert.equal(button.props.title, "知识库工作台");
  assert.equal(button.props["aria-label"], "知识库工作台");
  assert.equal(button.props["aria-pressed"], false);
  assert.doesNotMatch(button.props.className, /dsh-kb-entry-active/);
  assert.ok(childrenOf(button).some((child) => child?.type === "span" && child.props?.children === "知识库"));

  const collapsedTree = renderAction(mod, false);
  const collapsed = findChild(collapsedTree, (child) => child?.type === "button");
  assert.match(collapsed.props.className, /dsh-kb-entry-collapsed/);
  assert.ok(!childrenOf(collapsed).some((child) => child?.type === "span"));

  button.props.onClick();
  assert.equal(state.open, true);
});

test("open state renders an active entry and a portal modal with /kb/ iframe", () => {
  const { mod, state } = loadClient({ open: true, document: fakeDocument });
  const tree = renderAction(mod);
  const button = findChild(tree, (child) => child?.type === "button");
  assert.equal(button.props["aria-pressed"], true);
  assert.match(button.props.className, /dsh-kb-entry-active/);

  const portal = findChild(tree, (child) => child?.type === "portal");
  assert.ok(portal, "portal modal missing");
  assert.equal(portal.container, state.document.body, "portal should target document.body");
  const modal = findChild(portal.node, (child) => child?.props?.className === "dsh-kb-modal");
  assert.ok(modal, "modal missing");
  const frame = findChild(modal, (child) => child?.props?.className === "dsh-kb-modal-frame");
  assert.equal(frame.type, "iframe");
  assert.equal(frame.props.src, "/kb/?embed=1");
  assert.equal(frame.props.title, "知识库工作台");
  const head = findChild(modal, (child) => child?.props?.className === "dsh-kb-modal-head");
  const close = findChild(head, (child) => child?.props?.className === "dsh-kb-modal-close");
  assert.ok(close, "close button missing");
  close.props.onClick();
  assert.equal(state.open, false);
});

test("injects the sidebar and modal CSS once", () => {
  const { mod, state } = loadClient({ document: fakeDocument });
  const ctx = {
    slots: {
      inject(_name, callback) { callback(); },
      register() {},
    },
  };
  mod.apply(ctx);
  mod.apply(ctx);
  assert.equal(state.styles.length, 1);
  assert.match(state.styles[0].textContent, /\.dsh-kb-entry/);
  assert.match(state.styles[0].textContent, /\.dsh-kb-modal-backdrop/);
});

test("bundle registers the loader entry id used by the profile", () => {
  const boot = (ids) => ({ __DSH_BOOT__: { entries: ids.map((id) => ({ id })) } });
  assert.equal(loadClient({ window: boot(["dsh-knowledge-base"]) }).entry.id, "dsh-knowledge-base");
  assert.equal(loadClient({ window: boot(["dsh-knowledge-wiki"]) }).entry.id, "dsh-knowledge-wiki");
  assert.equal(loadClient().entry.id, "dsh-knowledge-base");
});
