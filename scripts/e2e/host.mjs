/**
 * E2E 宿主：临时 DSH web profile + 临时 kbRoot。
 *
 * 只做三件事：
 *  1. 从真实 `web` profile 复制启动所需配置，软链 node_modules；
 *  2. 写一份只含本插件的临时 cordis.patch.yml，指向临时 kbRoot；
 *  3. 启动 `dsh --profile <e2e-xxxxxx> --port <free> --no-open`，轮询 /kb/api/status。
 *
 * 清理时只删除本脚本自己创建的路径（profile 名以 e2e- 开头、kbRoot 名以
 * kb-e2e- 开头），绝不触碰真实 `~/.dsh/profiles/web` 或用户知识库。
 */
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import { cp, mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { createServer } from "node:net";
import { homedir, tmpdir } from "node:os";
import { basename, dirname, join, resolve, sep } from "node:path";
import { randomBytes } from "node:crypto";

const PROFILE_FILES = [
  "cordis.yml",
  "cordis.patch.yml",
  "package.json",
  "pnpm-lock.yaml",
  "pnpm-workspace.yaml",
];

const DEFAULT_STATUS_TIMEOUT_MS = 60_000;
const STATUS_POLL_MS = 250;
const KILL_GRACE_MS = 8_000;

export class HostError extends Error {
  constructor(message, details = "") {
    super(details ? `${message}\n${details}` : message);
    this.name = "HostError";
  }
}

/** `$DSH_HOME`（默认 ~/.dsh）；测试宿主 profile 必须放在它的 profiles/ 下。 */
export function dshHome(env = process.env) {
  const configured = String(env?.DSH_HOME ?? "").trim();
  if (configured === "") return join(homedir(), ".dsh");
  return resolve(configured.startsWith("~/") ? join(homedir(), configured.slice(2)) : configured);
}

/** 进程退出/启动失败时的兜底日志格式。 */
export function createLogCapture(limit = 4000) {
  const stdout = [];
  const stderr = [];
  return {
    stdout,
    stderr,
    push(kind, chunk) {
      const bucket = kind === "stderr" ? stderr : stdout;
      bucket.push(String(chunk));
      if (bucket.length > limit) bucket.splice(0, bucket.length - limit);
    },
    text() {
      return [
        ...(stdout.length > 0 ? ["----- stdout -----", stdout.join("").trimEnd()] : []),
        ...(stderr.length > 0 ? ["----- stderr -----", stderr.join("").trimEnd()] : []),
      ].join("\n");
    },
    tailLines(count = 80) {
      return this.text().split(/\r?\n/).slice(-count).join("\n");
    },
  };
}

function assertSafeProfileDir(profileDir, profileName, home) {
  const profilesRoot = resolve(home, "profiles");
  const absolute = resolve(profileDir);
  const expected = join(profilesRoot, profileName);
  if (absolute !== expected || !basename(absolute).startsWith("e2e-")) {
    throw new HostError(`拒绝删除非 E2E 临时 profile：${absolute}`);
  }
}

function assertSafeKbRoot(kbRoot) {
  const absolute = resolve(kbRoot);
  const tempRoot = resolve(tmpdir());
  if (!absolute.startsWith(`${tempRoot}${sep}`) || !basename(absolute).startsWith("kb-e2e-")) {
    throw new HostError(`拒绝删除非 E2E 临时 kbRoot：${absolute}`);
  }
}

/** 选一个当前空闲的 127.0.0.1 端口；与随后 spawn 的竞态用状态轮询兜底。 */
export async function findFreePort() {
  return new Promise((resolvePort, reject) => {
    const server = createServer();
    server.unref();
    server.once("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const address = server.address();
      const port = typeof address === "object" && address ? address.port : 0;
      server.close(() => (port > 0 ? resolvePort(port) : reject(new HostError("无法分配空闲端口"))));
    });
  });
}

/**
 * 生成临时 patch：保留真实 profile 的其它插件配置，删掉知识插件/旧验收块/HMR，
 * 再插入一条只指向临时 kbRoot 的 knowledge-wiki。HMR 在 E2E 中会监听源码导致
 * 长跑时偶发重载，因此一律去掉。
 */
export function rewritePatch(sourceText, kbRoot) {
  const lines = String(sourceText ?? "").split(/\r?\n/);
  const starts = [];
  for (let i = 0; i < lines.length; i += 1) {
    if (/^-\s/.test(lines[i])) starts.push(i);
  }
  const preamble = starts.length === 0 ? lines : lines.slice(0, starts[0]);
  const kept = [];
  const dropped = [];
  for (let i = 0; i < starts.length; i += 1) {
    const block = lines.slice(starts[i], i + 1 < starts.length ? starts[i + 1] : lines.length);
    const text = block.join("\n");
    const drop = /dsh-knowledge-(wiki|base)|id:\s*knowledge-(base|wiki)|^\s*kbRoot:\s/m.test(text)
      || /^\s*id:\s*hmr\s*$/m.test(text)
      || /kb-e2e-|e2e-[0-9a-f]{6}|\/tmp\/kb-|kb-[0-9a-z]+-accept|acceptance/i.test(text);
    if (drop) dropped.push(text.trim().split(/\r?\n/)[0]);
    else kept.push(block);
  }
  const body = kept.map((block) => block.join("\n").replace(/\s+$/, "")).filter((text) => text !== "");
  const generated = `- insert:
    - id: knowledge-base
      name: dsh-knowledge-wiki
      config:
        kbRoot: ${JSON.stringify(kbRoot)}
        defaultKb: default`;
  const preambleText = preamble
    .filter((line) => !/dsh-knowledge|install-to-machine/i.test(line))
    .join("\n")
    .trim();
  const output = [
    "# Generated by scripts/e2e/run.mjs — ephemeral E2E patch; do not edit.",
    ...(preambleText === "" ? [] : [preambleText]),
    ...body,
    generated,
    "",
  ].join("\n\n").replace(/\n{3,}/g, "\n\n");
  const occurrences = output.match(/name:\s*dsh-knowledge-wiki/g) ?? [];
  if (occurrences.length !== 1) {
    throw new HostError(`临时 patch 中知识插件应恰好出现一次，实际 ${occurrences.length} 次`);
  }
  if (!output.includes(`kbRoot: ${JSON.stringify(kbRoot)}`)) {
    throw new HostError("临时 patch 未写入 kbRoot");
  }
  return { text: output, dropped };
}

async function waitForStatus(baseUrl, { timeoutMs, child, logs, getSpawnError = () => null }) {
  const started = Date.now();
  let lastError = "";
  while (Date.now() - started < timeoutMs) {
    const spawnError = getSpawnError();
    if (spawnError) {
      throw new HostError(`无法启动 dsh：${String(spawnError?.message ?? spawnError)}`, logs.tailLines(80));
    }
    if (child && (child.exitCode !== null || child.signalCode !== null)) {
      throw new HostError(`DSH 宿主提前退出（code=${child.exitCode}）`, logs.tailLines(120));
    }
    try {
      const response = await fetch(`${baseUrl}/kb/api/status`, { signal: AbortSignal.timeout(3000) });
      if (response.ok) return await response.json();
      lastError = `HTTP ${response.status}`;
    } catch (error) {
      lastError = String(error?.cause?.code ?? error?.message ?? error);
    }
    await new Promise((done) => setTimeout(done, STATUS_POLL_MS));
  }
  throw new HostError(`等待 /kb/api/status 超时（${timeoutMs}ms，最后错误：${lastError}）`, logs.tailLines(120));
}

/** 杀掉 dsh 进程树：POSIX 下用进程组，Windows 用 taskkill。 */
async function killTree(child) {
  if (!child || child.exitCode !== null || child.signalCode !== null) return;
  const pid = child.pid;
  if (!pid) return;
  try {
    if (process.platform === "win32") {
      spawn("taskkill", ["/pid", String(pid), "/T", "/F"], { stdio: "ignore", windowsHide: true });
    } else {
      process.kill(-pid, "SIGTERM");
    }
  } catch {
    try { child.kill("SIGTERM"); } catch { /* already gone */ }
  }
  const exited = await Promise.race([
    new Promise((done) => child.once("exit", () => done(true))),
    new Promise((done) => setTimeout(() => done(false), KILL_GRACE_MS)),
  ]);
  if (exited) return;
  try {
    if (process.platform === "win32") {
      spawn("taskkill", ["/pid", String(pid), "/T", "/F"], { stdio: "ignore", windowsHide: true });
    } else {
      process.kill(-pid, "SIGKILL");
    }
  } catch {
    try { child.kill("SIGKILL"); } catch { /* already gone */ }
  }
  await Promise.race([
    new Promise((done) => child.once("exit", done)),
    new Promise((done) => setTimeout(done, 2000)),
  ]);
}

async function makeTempProfile({ sourceProfile, home, kbRoot, log }) {
  const sourceDir = join(home, "profiles", sourceProfile);
  if (!existsSync(sourceDir)) throw new HostError(`真实 profile 不存在：${sourceDir}`);
  const profileName = `e2e-${randomBytes(3).toString("hex")}`;
  const profileDir = join(home, "profiles", profileName);
  await mkdir(profileDir, { recursive: true });
  try {
    for (const name of PROFILE_FILES) {
      const from = join(sourceDir, name);
      if (!existsSync(from)) {
        if (name === "cordis.patch.yml") {
          await writeFile(join(profileDir, name), "", "utf8");
          continue;
        }
        throw new HostError(`真实 profile 缺少 ${name}：${from}`);
      }
      await cp(from, join(profileDir, name));
    }
    const sourceModules = join(sourceDir, "node_modules");
    if (!existsSync(sourceModules)) {
      throw new HostError(`真实 profile 缺少 node_modules，无法离线启动：${sourceModules}`);
    }
    await symlink(sourceModules, join(profileDir, "node_modules"), process.platform === "win32" ? "junction" : "dir");
    const sourcePatch = await readFile(join(sourceDir, "cordis.patch.yml"), "utf8").catch(() => "");
    const { text, dropped } = rewritePatch(sourcePatch, kbRoot);
    await writeFile(join(profileDir, "cordis.patch.yml"), text, "utf8");
    if (dropped.length > 0) log(`temp profile: dropped patch blocks ${JSON.stringify(dropped)}`);
    return { profileName, profileDir, sourceDir };
  } catch (error) {
    await rm(profileDir, { recursive: true, force: true }).catch(() => {});
    throw error;
  }
}

/**
 * DSH_E2E_URL：复用已经启动的宿主。这里只读 /kb/api/status 拿 kbRoot，
 * 并拒绝在非临时目录上执行任何写操作（除非显式 DSH_E2E_ALLOW_MUTATE=1）。
 */
async function connectExternal(baseUrl) {
  let status;
  try {
    const response = await fetch(`${baseUrl}/kb/api/status`, { signal: AbortSignal.timeout(10_000) });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    status = await response.json();
  } catch (error) {
    throw new HostError(`DSH_E2E_URL 不可用：${baseUrl}（${String(error?.message ?? error)}）`);
  }
  const kbRoot = String(status?.kbRoot ?? "");
  if (kbRoot === "") throw new HostError("DSH_E2E_URL 的 /kb/api/status 未返回 kbRoot");
  return {
    mode: "external",
    baseUrl: baseUrl.replace(/\/+$/, ""),
    kbRoot: resolve(kbRoot),
    profileName: "(external)",
    profileDir: "",
    status,
  };
}

/**
 * 启动（或连接）E2E 宿主。
 * @returns {Promise<{mode, baseUrl, kbRoot, profileName, profileDir, status, logs, stop, keep}>}
 */
export async function startHost({
  artifactsDir,
  env = process.env,
  statusTimeoutMs = DEFAULT_STATUS_TIMEOUT_MS,
  log = () => {},
} = {}) {
  const external = String(env?.DSH_E2E_URL ?? "").trim();
  if (external !== "") {
    const host = await connectExternal(external);
    host.logs = createLogCapture();
    host.keep = false;
    host.stop = async () => {};
    log(`using external DSH host ${host.baseUrl} (kbRoot=${host.kbRoot})`);
    return host;
  }

  const home = dshHome(env);
  const sourceProfile = String(env?.DSH_E2E_SOURCE_PROFILE ?? "web").trim() || "web";
  const logs = createLogCapture();
  const kbRoot = await mkdtemp(join(tmpdir(), "kb-e2e-"));
  const temp = await makeTempProfile({ sourceProfile, home, kbRoot, log });
  const port = await findFreePort();
  const baseUrl = `http://127.0.0.1:${port}`;
  const bin = String(env?.DSH_E2E_DSH_BIN ?? "dsh");
  const args = ["--profile", temp.profileName, "--port", String(port), "--no-open"];
  log(`starting ${bin} ${args.join(" ")}`);
  const child = spawn(bin, args, {
    cwd: temp.profileDir,
    detached: process.platform !== "win32",
    env: {
      ...env,
      DSH_E2E: "1",
      NO_COLOR: "1",
      FORCE_COLOR: "0",
    },
    stdio: ["ignore", "pipe", "pipe"],
    windowsHide: true,
  });
  let spawnError = null;
  child.once("error", (error) => {
    spawnError = error;
    logs.push("stderr", `spawn error: ${String(error?.message ?? error)}\n`);
  });
  child.stdout?.on("data", (chunk) => {
    logs.push("stdout", chunk);
    if (String(env?.DSH_E2E_VERBOSE ?? "") !== "") process.stdout.write(`[dsh] ${chunk}`);
  });
  child.stderr?.on("data", (chunk) => {
    logs.push("stderr", chunk);
    if (String(env?.DSH_E2E_VERBOSE ?? "") !== "") process.stderr.write(`[dsh] ${chunk}`);
  });

  let stopped = false;
  const keep = String(env?.DSH_E2E_KEEP ?? "") !== "";
  const stop = async () => {
    if (stopped) return;
    stopped = true;
    await killTree(child);
    await writeFile(join(artifactsDir, "host.log"), logs.text(), "utf8").catch(() => {});
    if (keep) {
      log(`DSH_E2E_KEEP=1: keeping profile ${temp.profileDir} and kbRoot ${kbRoot}`);
      return;
    }
    try {
      assertSafeProfileDir(temp.profileDir, temp.profileName, home);
      assertSafeKbRoot(kbRoot);
    } catch (error) {
      log(`cleanup safety check failed: ${String(error?.message ?? error)}`);
      return;
    }
    await rm(temp.profileDir, { recursive: true, force: true }).catch(() => {});
    await rm(kbRoot, { recursive: true, force: true }).catch(() => {});
  };

  try {
    await writeFile(join(artifactsDir, "host.log"), logs.text(), "utf8");
    const status = await waitForStatus(baseUrl, { timeoutMs: statusTimeoutMs, child, logs, getSpawnError: () => spawnError });
    if (resolve(String(status?.kbRoot ?? "")) !== resolve(kbRoot)) {
      throw new HostError(
        `宿主 kbRoot 与预期不一致：status=${status?.kbRoot} expected=${kbRoot}`,
        logs.tailLines(80),
      );
    }
    log(`DSH host ready at ${baseUrl} (profile ${temp.profileName}, kbRoot ${kbRoot})`);
    return {
      mode: "self",
      baseUrl,
      kbRoot,
      profileName: temp.profileName,
      profileDir: temp.profileDir,
      sourceProfileDir: temp.sourceDir,
      status,
      logs,
      child,
      keep,
      stop,
    };
  } catch (error) {
    await stop();
    throw error;
  }
}

