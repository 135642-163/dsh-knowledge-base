/**
 * 把 src/client/index.tsx 打成 DSH 客户端 bundle：
 * CJS + window.__ModuleLoader__.load({ id, factory })。
 * 用法：node scripts/build-client.mjs [--check]
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const entry = join(root, "src/client/index.tsx");
const outfile = join(root, "lib/client.js");
const check = process.argv.includes("--check");
const banner = "// Generated by scripts/build-client.mjs. Do not edit by hand.\n";

function indentLines(text, spaces) {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length === 0 ? "" : `${pad}${line}`))
    .join("\n");
}

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  external: ["react", "react/jsx-runtime", "react-dom"],
  charset: "utf8",
  legalComments: "none",
  logLevel: "silent",
});

const body = result.outputFiles[0].text.trimEnd();
const wrapped = `${banner}(() => {
  const KB_CLIENT_IDS = ["dsh-knowledge-base", "dsh-knowledge-wiki"];
  const boot = typeof window !== "undefined" ? window.__DSH_BOOT__ : undefined;
  const rows = boot && Array.isArray(boot.entries) ? boot.entries : [];
  const known = new Set(rows.map((row) => row && row.id));
  const id = KB_CLIENT_IDS.find((candidate) => known.has(candidate)) || KB_CLIENT_IDS[0];
  window.__ModuleLoader__.load({
    id,
    factory: (require) => {
      var module = { exports: {} };
      var exports = module.exports;
      (function (module, exports, require) {
${indentLines(body, 8)}
      })(module, exports, require);
      return module.exports;
    }
  });
})();
`;

if (check) {
  let current = "";
  try {
    current = await readFile(outfile, "utf8");
  } catch {
    current = "";
  }
  if (current !== wrapped) {
    console.error("client bundle is stale: run `npm run build:client`");
    process.exitCode = 1;
  } else {
    console.log("client bundle is up to date");
  }
} else {
  await writeFile(outfile, wrapped, "utf8");
  console.log(`wrote ${outfile} (${Buffer.byteLength(wrapped)} bytes)`);
}
